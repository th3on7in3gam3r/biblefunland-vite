export function filterPlayFeatures(features, { age = [], category = [], type = [] } = {}) {
  return features.filter((item) => {
    const hasAge = !age.length || age.includes(item.age);
    const hasCategory = !category.length || category.includes(item.category);
    const hasType = !type.length || type.includes(item.type);
    return hasAge && hasCategory && hasType;
  });
}

export function getFeaturedPlayFeatures(features = PLAY_FEATURES) {
  return features.filter((f) => f.hot);
}
